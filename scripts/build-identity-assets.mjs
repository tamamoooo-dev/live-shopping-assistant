// Build the small UI index from the reviewed source catalogue.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'data/identity-assets.json'), 'utf8'));
const kinds = new Set(['logo', 'reconstructed-logo', 'name-mark', 'packaging']);
function index(entries) {
  return Object.fromEntries(Object.entries(entries).map(([id, asset]) => {
    if (!kinds.has(asset.kind)) throw new Error(`Unknown kind for ${id}`);
    const absolute = path.resolve(root, asset.file);
    if (!absolute.startsWith(path.join(root, 'icons') + path.sep) || !fs.existsSync(absolute)) throw new Error(`Missing/invalid asset: ${id}`);
    if (asset.background && !/^#[a-f0-9]{6}$/i.test(asset.background)) throw new Error(`Invalid background for ${id}`);
    return [id, { file: asset.file, kind: asset.kind, ...(asset.background ? {background: asset.background} : {}) }];
  }));
}
const stores = index(manifest.stores), brands = index(manifest.brands);
fs.writeFileSync(path.join(root, 'src/identityAssets.js'), `// Generated by scripts/build-identity-assets.mjs; provenance: data/identity-assets.json.\nexport const STORE_ASSETS = ${JSON.stringify(stores)};\nexport const BRAND_ASSETS = ${JSON.stringify(brands)};\n`);
